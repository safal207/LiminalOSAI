"""Fixed separate receiver-source process: public enrollment and readonly issue.

The private Ed25519 key is generated by this child and never crosses its protocol.
The collector can request evidence for a challenge, not supply an export to sign.
This is process separation on one trusted host, not separate administration or an
OS sandbox for a hostile controller. Public receiver arguments need their own
issuer-side redaction contract before sensitive workloads are connected.
"""
